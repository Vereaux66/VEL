class StrategyManager:
    """
    Manages multiple trading strategies and coordinates execution.
    
    Features:
    - Multi-strategy coordination
    - Signal aggregation and prioritization
    - Risk budget allocation
    - Performance monitoring
    """

    def __init__(self):
        """Initialize strategy manager."""
        self._strategies: Dict[StrategyType, BaseStrategy] = {}
        self._lock = threading.Lock()
        self._is_running = False
        self._scan_thread: Optional[threading.Thread] = None
        self._pending_signals: deque = deque(maxlen=1000)

    def register_strategy(self, strategy: BaseStrategy):
        """Register a strategy with the manager."""
        with self._lock:
            self._strategies[strategy.strategy_type] = strategy
            logger.info(
                "Strategy registered: %s",
                strategy.strategy_type.value,
            )

    def unregister_strategy(self, strategy_type: StrategyType):
        """Unregister a strategy."""
        with self._lock:
            if strategy_type in self._strategies:
                del self._strategies[strategy_type]
                logger.info("Strategy unregistered: %s", strategy_type.value)

    def get_strategy(self, strategy_type: StrategyType) -> Optional[BaseStrategy]:
        """Get a registered strategy."""
        with self._lock:
            return self._strategies.get(strategy_type)

    def get_all_strategies(self) -> List[BaseStrategy]:
        """Get all registered strategies."""
        with self._lock:
            return list(self._strategies.values())

    def scan_for_signals(
        self,
        market_data: Dict[str, Any],
    ) -> List[TradingSignal]:
        """
        Scan all strategies for trading signals.
        
        Args:
            market_data: Current market state
            
        Returns:
            Aggregated list of signals from all strategies
        """
        all_signals = []
        
        with self._lock:
            strategies = list(self._strategies.values())
        
        for strategy in strategies:
            can_execute, reason = strategy.can_execute()
            if not can_execute:
                logger.debug(
                    "Strategy %s cannot execute: %s",
                    strategy.strategy_type.value,
                    reason,
                )
                continue
            
            try:
                signals = strategy.generate_signals(market_data)
                all_signals.extend(signals)
            except Exception as e:
                logger.error(
                    "Strategy %s signal generation failed: %s",
                    strategy.strategy_type.value,
                    e,
                )
        
        # Sort by confidence (highest first)
        all_signals.sort(key=lambda s: s.confidence, reverse=True)
        
        return all_signals

    def start_continuous_scanning(
        self,
        market_data_provider: Callable[[], Dict[str, Any]],
        signal_handler: Callable[[TradingSignal], None],
        interval_seconds: float = 5.0,
    ):
        """
        Start continuous market scanning.
        
        Args:
            market_data_provider: Function that returns current market data
            signal_handler: Function to handle generated signals
            interval_seconds: Scan interval
        """
        if self._is_running:
            logger.warning("Scanner already running")
            return
        
        self._is_running = True
        
        def scan_loop():
            while self._is_running:
                try:
                    market_data = market_data_provider()
                    signals = self.scan_for_signals(market_data)
                    
                    for signal in signals:
                        signal_handler(signal)
                        self._pending_signals.append(signal)
                    
                except Exception as e:
                    logger.error("Scan loop error: %s", e)
                
                time.sleep(interval_seconds)
        
        self._scan_thread = threading.Thread(target=scan_loop, daemon=True)
        self._scan_thread.start()
        logger.info("Continuous scanning started with %.1fs interval", interval_seconds)

    def stop_continuous_scanning(self):
        """Stop continuous scanning."""
        self._is_running = False
        if self._scan_thread:
            self._scan_thread.join(timeout=5.0)
            self._scan_thread = None
        logger.info("Continuous scanning stopped")

    def get_aggregated_metrics(self) -> Dict[str, StrategyMetrics]:
        """Get metrics for all strategies."""
        metrics = {}
        with self._lock:
            for strategy_type, strategy in self._strategies.items():
                metrics[strategy_type.value] = strategy.get_metrics()
        return metrics

    def pause_all(self):
        """Pause all strategies."""
        with self._lock:
            for strategy in self._strategies.values():
                strategy.pause()
        logger.info("All strategies paused")

    def resume_all(self):
        """Resume all strategies."""
        with self._lock:
            for strategy in self._strategies.values():
                strategy.resume()
        logger.info("All strategies resumed")


