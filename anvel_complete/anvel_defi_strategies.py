class BaseStrategy(ABC):
    """
    Abstract base class for all trading strategies.
    
    Provides:
    - Risk management framework
    - Signal generation interface
    - Execution hooks
    - Performance tracking
    """

    def __init__(
        self,
        config: StrategyConfig,
        price_feed: Optional[Callable[[str, int], Decimal]] = None,
    ):
        """
        Initialize strategy.
        
        Args:
            config: Strategy configuration
            price_feed: Optional callable to get price for token on chain
        """
        self.config = config
        self.price_feed = price_feed
        self.state = StrategyState.IDLE
        self.metrics = StrategyMetrics()
        
        self._lock = threading.Lock()
        self._last_execution_time = 0
        self._daily_loss = Decimal("0")
        self._daily_trades = 0
        self._trade_history: deque = deque(maxlen=1000)
        self._signals: deque = deque(maxlen=100)
        
        logger.info(
            "Strategy initialized: type=%s, enabled=%s",
            config.strategy_type.value,
            config.enabled,
        )

    @property
    def strategy_type(self) -> StrategyType:
        """Get strategy type."""
        return self.config.strategy_type

    @abstractmethod
    def generate_signals(self, market_data: Dict[str, Any]) -> List[TradingSignal]:
        """
        Generate trading signals based on market data.
        
        Args:
            market_data: Current market state including prices, volumes, etc.
            
        Returns:
            List of trading signals
        """
        pass

    @abstractmethod
    def validate_opportunity(
        self,
        signal: TradingSignal,
        current_prices: Dict[str, Decimal],
    ) -> bool:
        """
        Validate that an opportunity is still valid before execution.
        
        Args:
            signal: The trading signal to validate
            current_prices: Current market prices
            
        Returns:
            True if opportunity is still valid
        """
        pass

    def can_execute(self) -> Tuple[bool, str]:
        """
        Check if strategy can execute trades.
        
        Returns:
            Tuple of (can_execute, reason_if_not)
        """
        with self._lock:
            if not self.config.enabled:
                return False, "Strategy is disabled"
            
            if self.state == StrategyState.PAUSED:
                return False, "Strategy is paused"
            
            if self.state == StrategyState.ERROR:
                return False, "Strategy is in error state"
            
            # Check cooldown
            time_since_last = time.time() - self._last_execution_time
            if time_since_last < self.config.cooldown_seconds:
                remaining = self.config.cooldown_seconds - time_since_last
                return False, f"Cooldown active: {remaining:.0f}s remaining"
            
            # Check daily loss limit
            if self._daily_loss >= self.config.max_daily_loss_pct:
                return False, "Daily loss limit reached"
            
            # Check hourly trade limit
            hour_ago = time.time() - 3600
            recent_trades = sum(
                1 for t in self._trade_history
                if t.get('timestamp', 0) > hour_ago
            )
            if recent_trades >= self.config.max_trades_per_hour:
                return False, "Hourly trade limit reached"
            
            return True, ""

    def calculate_position_size(
        self,
        available_capital: Decimal,
        signal: TradingSignal,
    ) -> Decimal:
        """
        Calculate appropriate position size based on risk parameters.
        
        Args:
            available_capital: Total available capital
            signal: Trading signal with confidence
            
        Returns:
            Position size in base currency
        """
        # Base size from max position percentage
        max_size = available_capital * self.config.max_position_size_pct
        
        # Adjust by signal confidence (higher confidence = larger position)
        confidence_adjusted = max_size * Decimal(str(signal.confidence))
        
        # Ensure minimum viable position
        min_position = Decimal("10.00")  # $10 minimum
        
        return max(min_position, min(confidence_adjusted, max_size))

    def record_trade(
        self,
        signal: TradingSignal,
        executed: bool,
        profit: Optional[Decimal] = None,
        error: Optional[str] = None,
    ):
        """Record trade for metrics tracking."""
        with self._lock:
            self._trade_history.append({
                'signal_id': signal.signal_id,
                'timestamp': time.time(),
                'executed': executed,
                'profit': float(profit) if profit else None,
                'error': error,
            })
            
            self.metrics.total_signals += 1
            
            if executed:
                self.metrics.executed_signals += 1
                self._last_execution_time = time.time()
                self._daily_trades += 1
                
                if profit:
                    if profit > 0:
                        self.metrics.profitable_trades += 1
                        self.metrics.total_profit += profit
                    else:
                        self.metrics.losing_trades += 1
                        self.metrics.total_loss += abs(profit)
                        self._daily_loss += abs(profit)
            
            # Update win rate
            total_closed = self.metrics.profitable_trades + self.metrics.losing_trades
            if total_closed > 0:
                self.metrics.win_rate = self.metrics.profitable_trades / total_closed
                
                # Average profit per trade
                net = self.metrics.total_profit - self.metrics.total_loss
                self.metrics.avg_profit_per_trade = net / Decimal(total_closed)

    def reset_daily_metrics(self):
        """Reset daily tracking metrics (call at day boundary)."""
        with self._lock:
            self._daily_loss = Decimal("0")
            self._daily_trades = 0

    def pause(self):
        """Pause strategy execution."""
        with self._lock:
            self.state = StrategyState.PAUSED
            logger.info("Strategy paused: %s", self.config.strategy_type.value)

    def resume(self):
        """Resume strategy execution."""
        with self._lock:
            if self.state == StrategyState.PAUSED:
                self.state = StrategyState.IDLE
                logger.info("Strategy resumed: %s", self.config.strategy_type.value)

    def get_metrics(self) -> StrategyMetrics:
        """Get current strategy metrics."""
        with self._lock:
            return self.metrics


