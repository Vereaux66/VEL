class MeanReversionStrategy(BaseStrategy):
    """
    Mean reversion strategy for DEX trading.
    
    Identifies overbought/oversold conditions and trades the reversion.
    
    Features:
    - Bollinger Band analysis
    - RSI-based entry/exit
    - Standard deviation thresholds
    - Convergence detection
    """

    def __init__(
        self,
        config: StrategyConfig,
        price_feed: Optional[Callable[[str, int], Decimal]] = None,
    ):
        super().__init__(config, price_feed)
        
        # Mean reversion specific config
        self.lookback_period = config.custom_params.get('lookback_period', 20)
        self.std_dev_threshold = config.custom_params.get('std_dev_threshold', 2.0)
        self.rsi_oversold = config.custom_params.get('rsi_oversold', 30)
        self.rsi_overbought = config.custom_params.get('rsi_overbought', 70)

    def generate_signals(self, market_data: Dict[str, Any]) -> List[TradingSignal]:
        """Generate mean reversion signals."""
        signals = []
        
        prices = market_data.get('prices', {})
        price_history = market_data.get('price_history', {})
        
        for chain_id in self.config.chain_ids or SUPPORTED_CHAINS.keys():
            chain_prices = prices.get(chain_id, {})
            
            for dex_name in self.config.dex_names or SUPPORTED_DEXES.keys():
                dex_prices = chain_prices.get(dex_name, {})
                
                for token, current_price in dex_prices.items():
                    history_key = f"{chain_id}:{dex_name}:{token}"
                    token_history = price_history.get(history_key, [])
                    
                    if len(token_history) < self.lookback_period:
                        continue
                    
                    # Calculate statistics
                    recent_prices = [float(p) for p in token_history[-self.lookback_period:]]
                    mean_price = statistics.mean(recent_prices)
                    std_dev = statistics.stdev(recent_prices) if len(recent_prices) > 1 else 0
                    
                    if std_dev == 0:
                        continue
                    
                    # Calculate z-score (how many std devs from mean)
                    z_score = (float(current_price) - mean_price) / std_dev
                    
                    # Calculate RSI
                    rsi = self._calculate_rsi(recent_prices)
                    
                    # Generate signals for extreme deviations
                    signal_type = None
                    confidence = 0.0
                    
                    # Oversold - expect price to rise
                    if z_score < -self.std_dev_threshold and rsi < self.rsi_oversold:
                        signal_type = SignalType.BUY
                        confidence = min(1.0, abs(z_score) / 3)  # Max confidence at 3 std devs
                    
                    # Overbought - expect price to fall
                    elif z_score > self.std_dev_threshold and rsi > self.rsi_overbought:
                        signal_type = SignalType.SELL
                        confidence = min(1.0, abs(z_score) / 3)
                    
                    if signal_type and confidence >= 0.5:
                        expected_profit_bps = int(abs(z_score) * 50)  # 50bps per std dev
                        
                        signals.append(TradingSignal(
                            signal_id=f"MR-{secrets.token_hex(8).upper()}",
                            strategy_type=StrategyType.MEAN_REVERSION,
                            signal_type=signal_type,
                            chain_id=chain_id,
                            dex_name=dex_name,
                            token_in="USDC" if signal_type == SignalType.BUY else token,
                            token_out=token if signal_type == SignalType.BUY else "USDC",
                            amount=Decimal("0"),
                            expected_output=Decimal("0"),
                            expected_profit_bps=expected_profit_bps,
                            confidence=confidence,
                            timestamp=int(time.time()),
                            expires_at=int(time.time()) + 600,  # 10 minute validity
                            metadata={
                                'z_score': z_score,
                                'rsi': rsi,
                                'mean_price': mean_price,
                                'std_dev': std_dev,
                            }
                        ))
        
        return signals

    def _calculate_rsi(self, prices: List[float], period: int = 14) -> float:
        """Calculate RSI indicator."""
        if len(prices) < period + 1:
            return 50.0  # Neutral default
        
        gains = []
        losses = []
        
        for i in range(1, len(prices)):
            change = prices[i] - prices[i-1]
            if change > 0:
                gains.append(change)
                losses.append(0)
            else:
                gains.append(0)
                losses.append(abs(change))
        
        avg_gain = sum(gains[-period:]) / period
        avg_loss = sum(losses[-period:]) / period
        
        if avg_loss == 0:
            return 100.0
        
        rs = avg_gain / avg_loss
        rsi = 100 - (100 / (1 + rs))
        
        return rsi

    def validate_opportunity(
        self,
        signal: TradingSignal,
        current_prices: Dict[str, Decimal],
    ) -> bool:
        """Validate mean reversion signal."""
        if not signal.is_valid():
            return False
        
        # Ensure price hasn't already reverted significantly
        z_score = signal.metadata.get('z_score', 0)
        mean_price = signal.metadata.get('mean_price', 0)
        std_dev = signal.metadata.get('std_dev', 0)
        
        if not mean_price or not std_dev:
            return True
        
        token_key = f"{signal.chain_id}:{signal.dex_name}:{signal.token_out}"
        current_price = current_prices.get(token_key)
        
        if not current_price:
            return True
        
        # Calculate current z-score
        current_z = (float(current_price) - mean_price) / std_dev if std_dev else 0
        
        # Signal still valid if price is still extreme
        return abs(current_z) >= self.std_dev_threshold * 0.7


