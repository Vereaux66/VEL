class MomentumStrategy(BaseStrategy):
    """
    Momentum/trend following strategy for DEX trading.
    
    Identifies and follows strong price trends across DEX markets.
    Uses multiple timeframe analysis and volume confirmation.
    
    Features:
    - Multi-timeframe trend detection
    - Volume-weighted momentum scoring
    - Breakout detection
    - Trend strength filtering
    """

    def __init__(
        self,
        config: StrategyConfig,
        price_feed: Optional[Callable[[str, int], Decimal]] = None,
    ):
        super().__init__(config, price_feed)
        
        # Momentum-specific configuration
        self.lookback_periods = config.custom_params.get('lookback_periods', [5, 15, 60])  # minutes
        self.min_trend_strength = config.custom_params.get('min_trend_strength', 0.6)
        self.volume_confirmation_multiplier = config.custom_params.get('volume_multiplier', 1.5)
        
        # Price history for analysis
        self._price_history: Dict[str, deque] = {}
        self._volume_history: Dict[str, deque] = {}

    def generate_signals(self, market_data: Dict[str, Any]) -> List[TradingSignal]:
        """
        Generate momentum signals based on trend analysis.
        
        Args:
            market_data: Should contain:
                - prices: Current prices
                - price_history: Historical prices
                - volumes: Current volumes
                - volume_history: Historical volumes
        """
        signals = []
        
        prices = market_data.get('prices', {})
        price_history = market_data.get('price_history', {})
        volumes = market_data.get('volumes', {})
        volume_history = market_data.get('volume_history', {})
        
        for chain_id in self.config.chain_ids or SUPPORTED_CHAINS.keys():
            chain_prices = prices.get(chain_id, {})
            
            for dex_name in self.config.dex_names or SUPPORTED_DEXES.keys():
                dex_prices = chain_prices.get(dex_name, {})
                
                for token, current_price in dex_prices.items():
                    # Get historical data
                    history_key = f"{chain_id}:{dex_name}:{token}"
                    token_history = price_history.get(history_key, [])
                    token_volumes = volume_history.get(history_key, [])
                    
                    if len(token_history) < max(self.lookback_periods):
                        continue
                    
                    # Calculate momentum score
                    momentum_score = self._calculate_momentum_score(
                        current_price,
                        token_history,
                    )
                    
                    # Check volume confirmation
                    volume_confirmed = self._check_volume_confirmation(
                        token_volumes,
                        volumes.get(chain_id, {}).get(dex_name, {}).get(token, 0),
                    )
                    
                    if not volume_confirmed:
                        momentum_score *= 0.5  # Reduce confidence without volume
                    
                    # Generate signal if momentum is strong enough
                    if abs(momentum_score) >= self.min_trend_strength:
                        signal_type = SignalType.BUY if momentum_score > 0 else SignalType.SELL
                        
                        signals.append(TradingSignal(
                            signal_id=f"MOM-{secrets.token_hex(8).upper()}",
                            strategy_type=StrategyType.MOMENTUM,
                            signal_type=signal_type,
                            chain_id=chain_id,
                            dex_name=dex_name,
                            token_in="USDC" if signal_type == SignalType.BUY else token,
                            token_out=token if signal_type == SignalType.BUY else "USDC",
                            amount=Decimal("0"),  # Calculated at execution
                            expected_output=Decimal("0"),
                            expected_profit_bps=int(abs(momentum_score) * 100),
                            confidence=abs(momentum_score),
                            timestamp=int(time.time()),
                            expires_at=int(time.time()) + 300,  # 5 minute validity
                            metadata={
                                'momentum_score': momentum_score,
                                'volume_confirmed': volume_confirmed,
                                'trend_direction': 'up' if momentum_score > 0 else 'down',
                            }
                        ))
        
        return signals

    def _calculate_momentum_score(
        self,
        current_price: Decimal,
        price_history: List[Decimal],
    ) -> float:
        """
        Calculate momentum score across multiple timeframes.
        
        Returns:
            Score from -1.0 (strong downtrend) to 1.0 (strong uptrend)
        """
        if not price_history:
            return 0.0
        
        scores = []
        
        for period in self.lookback_periods:
            if len(price_history) < period:
                continue
            
            # Get price from 'period' bars ago
            past_price = price_history[-period]
            if past_price <= 0:
                continue
            
            # Calculate return
            returns = (float(current_price) - float(past_price)) / float(past_price)
            
            # Normalize to -1 to 1 (assuming ±10% is extreme)
            normalized = max(-1.0, min(1.0, returns / 0.10))
            scores.append(normalized)
        
        if not scores:
            return 0.0
        
        # Weight shorter timeframes more heavily
        weights = [1.0 / (i + 1) for i in range(len(scores))]
        weighted_sum = sum(s * w for s, w in zip(scores, weights))
        total_weight = sum(weights)
        
        return weighted_sum / total_weight

    def _check_volume_confirmation(
        self,
        volume_history: List[Decimal],
        current_volume: Decimal,
    ) -> bool:
        """Check if current volume confirms the trend."""
        if not volume_history or current_volume <= 0:
            return False
        
        avg_volume = sum(volume_history) / len(volume_history)
        
        return current_volume >= avg_volume * self.volume_confirmation_multiplier

    def validate_opportunity(
        self,
        signal: TradingSignal,
        current_prices: Dict[str, Decimal],
    ) -> bool:
        """Validate momentum signal is still valid."""
        if not signal.is_valid():
            return False
        
        # For momentum, just ensure price hasn't moved against us too much
        original_direction = signal.metadata.get('trend_direction')
        token_key = f"{signal.chain_id}:{signal.dex_name}:{signal.token_out}"
        current_price = current_prices.get(token_key)
        
        if not current_price:
            return True  # Can't validate, assume still valid
        
        return True  # Momentum signals remain valid within expiry


