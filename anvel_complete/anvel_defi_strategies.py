class DCAStrategy(BaseStrategy):
    """
    Dollar Cost Averaging strategy for systematic accumulation.
    
    Automatically accumulates tokens over time to reduce timing risk.
    
    Features:
    - Scheduled purchases at regular intervals
    - Dip buying (extra buys on significant drops)
    - Multi-token portfolio support
    - Rebalancing triggers
    """

    def __init__(
        self,
        config: StrategyConfig,
        price_feed: Optional[Callable[[str, int], Decimal]] = None,
    ):
        super().__init__(config, price_feed)
        
        # DCA specific config
        self.interval_hours = config.custom_params.get('interval_hours', 24)
        self.dip_buy_threshold_pct = config.custom_params.get('dip_buy_threshold_pct', 5.0)
        self.target_allocations = config.custom_params.get('target_allocations', {})
        
        # Track last buy times
        self._last_buy_times: Dict[str, float] = {}
        self._reference_prices: Dict[str, Decimal] = {}

    def generate_signals(self, market_data: Dict[str, Any]) -> List[TradingSignal]:
        """Generate DCA signals based on schedule and dips."""
        signals = []
        
        prices = market_data.get('prices', {})
        current_time = time.time()
        interval_seconds = self.interval_hours * 3600
        
        for chain_id in self.config.chain_ids or SUPPORTED_CHAINS.keys():
            chain_prices = prices.get(chain_id, {})
            
            for dex_name in self.config.dex_names or SUPPORTED_DEXES.keys():
                dex_prices = chain_prices.get(dex_name, {})
                
                for token, current_price in dex_prices.items():
                    token_key = f"{chain_id}:{dex_name}:{token}"
                    
                    # Check if token is in target allocations
                    if self.target_allocations and token not in self.target_allocations:
                        continue
                    
                    # Check scheduled buy
                    last_buy = self._last_buy_times.get(token_key, 0)
                    scheduled_buy = (current_time - last_buy) >= interval_seconds
                    
                    # Check for dip buy
                    ref_price = self._reference_prices.get(token_key)
                    dip_buy = False
                    dip_pct = 0.0
                    
                    if ref_price and current_price < ref_price:
                        dip_pct = float((ref_price - current_price) / ref_price) * 100
                        dip_buy = dip_pct >= self.dip_buy_threshold_pct
                    
                    if scheduled_buy or dip_buy:
                        confidence = 0.7 if scheduled_buy else min(0.9, 0.5 + dip_pct / 20)
                        
                        signals.append(TradingSignal(
                            signal_id=f"DCA-{secrets.token_hex(8).upper()}",
                            strategy_type=StrategyType.DCA,
                            signal_type=SignalType.BUY,
                            chain_id=chain_id,
                            dex_name=dex_name,
                            token_in="USDC",
                            token_out=token,
                            amount=Decimal("0"),  # Calculated at execution
                            expected_output=Decimal("0"),
                            expected_profit_bps=0,  # DCA doesn't predict short-term profit
                            confidence=confidence,
                            timestamp=int(current_time),
                            expires_at=int(current_time) + 3600,  # 1 hour validity
                            metadata={
                                'trigger': 'dip' if dip_buy else 'scheduled',
                                'dip_percentage': dip_pct if dip_buy else 0,
                                'interval_hours': self.interval_hours,
                            }
                        ))
                    
                    # Update reference price (highest seen)
                    if not ref_price or current_price > ref_price:
                        self._reference_prices[token_key] = current_price
        
        return signals

    def record_execution(self, token_key: str):
        """Record that a DCA buy was executed."""
        self._last_buy_times[token_key] = time.time()

    def validate_opportunity(
        self,
        signal: TradingSignal,
        current_prices: Dict[str, Decimal],
    ) -> bool:
        """DCA signals are always valid within expiry."""
        return signal.is_valid()


