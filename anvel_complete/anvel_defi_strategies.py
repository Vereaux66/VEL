class CrossChainArbitrageStrategy(BaseStrategy):
    """
    Cross-chain and cross-DEX arbitrage strategy.
    
    Detects and executes arbitrage opportunities across:
    - Different chains (e.g., ETH mainnet vs Arbitrum)
    - Different DEXes on the same chain (e.g., Uniswap vs Sushiswap)
    
    Features:
    - Atomic execution where possible
    - Gas cost consideration
    - Slippage protection
    - Bridge fee accounting for cross-chain arb
    """

    def __init__(
        self,
        config: StrategyConfig,
        price_feed: Optional[Callable[[str, int], Decimal]] = None,
        bridge_fee_estimator: Optional[Callable[[int, int, Decimal], Decimal]] = None,
    ):
        """
        Initialize arbitrage strategy.
        
        Args:
            config: Strategy configuration
            price_feed: Function to get token price on chain
            bridge_fee_estimator: Function to estimate bridge fees
        """
        super().__init__(config, price_feed)
        self.bridge_fee_estimator = bridge_fee_estimator
        
        # Arbitrage-specific configuration
        self.min_profit_after_fees_bps = config.custom_params.get('min_profit_after_fees_bps', 20)
        self.max_bridge_wait_seconds = config.custom_params.get('max_bridge_wait_seconds', 300)
        
        # Track opportunities
        self._opportunities: deque = deque(maxlen=100)

    def generate_signals(self, market_data: Dict[str, Any]) -> List[TradingSignal]:
        """
        Scan for arbitrage opportunities across chains and DEXes.
        
        Args:
            market_data: Should contain:
                - prices: Dict[chain_id][dex_name][token_address] = price
                - volumes: Dict[chain_id][dex_name][token_address] = volume
                - liquidity: Dict[chain_id][dex_name][token_address] = liquidity
                
        Returns:
            List of arbitrage signals
        """
        signals = []
        prices = market_data.get('prices', {})
        
        if not prices:
            return signals

        # Get all token addresses across all chains/dexes
        all_tokens = set()
        for chain_data in prices.values():
            for dex_data in chain_data.values():
                all_tokens.update(dex_data.keys())

        # For each token, find arbitrage opportunities
        for token in all_tokens:
            opportunities = self._find_arbitrage_opportunities(token, prices, market_data)
            
            for opp in opportunities:
                # Skip if profit too low
                if opp.profit_bps < self.config.min_profit_threshold_bps:
                    continue
                
                # Create signal
                signal = TradingSignal(
                    signal_id=self._generate_signal_id(),
                    strategy_type=StrategyType.ARBITRAGE,
                    signal_type=SignalType.BUY,
                    chain_id=opp.source_chain_id,
                    dex_name=opp.source_dex,
                    token_in=token,
                    token_out=token,  # Same token, different venue
                    amount=opp.max_amount,
                    expected_output=opp.max_amount * (Decimal("1") + Decimal(opp.profit_bps) / Decimal("10000")),
                    expected_profit_bps=opp.profit_bps,
                    confidence=self._calculate_confidence(opp),
                    timestamp=int(time.time()),
                    expires_at=int(time.time()) + 30,  # 30 second validity
                    metadata={
                        'opportunity': {
                            'source_chain': opp.source_chain_id,
                            'target_chain': opp.target_chain_id,
                            'source_dex': opp.source_dex,
                            'target_dex': opp.target_dex,
                            'is_cross_chain': opp.is_cross_chain,
                            'net_profit_estimate': float(opp.net_profit_estimate),
                        }
                    }
                )
                
                signals.append(signal)
                self._opportunities.append(opp)
        
        return signals

    def _find_arbitrage_opportunities(
        self,
        token: str,
        prices: Dict[int, Dict[str, Dict[str, Decimal]]],
        market_data: Dict[str, Any],
    ) -> List[ArbitrageOpportunity]:
        """Find all arbitrage opportunities for a token."""
        opportunities = []
        
        # Collect all price points for this token
        price_points = []
        for chain_id, chain_data in prices.items():
            for dex_name, dex_data in chain_data.items():
                if token in dex_data:
                    price_points.append({
                        'chain_id': chain_id,
                        'dex_name': dex_name,
                        'price': dex_data[token],
                    })
        
        if len(price_points) < 2:
            return opportunities
        
        # Compare all pairs
        for i, source in enumerate(price_points):
            for target in price_points[i+1:]:
                # Calculate price difference
                source_price = source['price']
                target_price = target['price']
                
                if source_price <= 0 or target_price <= 0:
                    continue
                
                # Determine direction (buy low, sell high)
                if source_price < target_price:
                    buy_venue = source
                    sell_venue = target
                    profit_bps = int(((target_price - source_price) / source_price) * 10000)
                else:
                    buy_venue = target
                    sell_venue = source
                    profit_bps = int(((source_price - target_price) / target_price) * 10000)
                
                if profit_bps < self.min_profit_after_fees_bps:
                    continue
                
                is_cross_chain = buy_venue['chain_id'] != sell_venue['chain_id']
                
                # Estimate costs
                gas_cost = self._estimate_gas_cost(
                    buy_venue['chain_id'],
                    sell_venue['chain_id'],
                    is_cross_chain,
                )
                
                bridge_cost = Decimal("0")
                if is_cross_chain and self.bridge_fee_estimator:
                    bridge_cost = self.bridge_fee_estimator(
                        buy_venue['chain_id'],
                        sell_venue['chain_id'],
                        Decimal("1000"),  # Estimate for $1000
                    )
                
                # Calculate net profit
                total_cost = gas_cost + bridge_cost
                trade_amount = Decimal("1000")  # Base calculation on $1000
                gross_profit = trade_amount * Decimal(profit_bps) / Decimal("10000")
                net_profit = gross_profit - total_cost
                
                if net_profit <= 0:
                    continue
                
                # Get max amount based on liquidity
                max_amount = self._get_max_trade_amount(
                    token,
                    buy_venue['chain_id'],
                    buy_venue['dex_name'],
                    market_data.get('liquidity', {}),
                )
                
                opportunities.append(ArbitrageOpportunity(
                    opportunity_id=self._generate_opportunity_id(),
                    source_chain_id=buy_venue['chain_id'],
                    source_dex=buy_venue['dex_name'],
                    target_chain_id=sell_venue['chain_id'],
                    target_dex=sell_venue['dex_name'],
                    token_address=token,
                    source_price=buy_venue['price'],
                    target_price=sell_venue['price'],
                    profit_bps=profit_bps,
                    max_amount=max_amount,
                    gas_cost_estimate=gas_cost,
                    net_profit_estimate=net_profit,
                    timestamp=int(time.time()),
                    is_cross_chain=is_cross_chain,
                ))
        
        return opportunities

    def _estimate_gas_cost(
        self,
        source_chain: int,
        target_chain: int,
        is_cross_chain: bool,
    ) -> Decimal:
        """Estimate gas cost for arbitrage execution."""
        # Base gas costs per chain type (in USD)
        chain = SUPPORTED_CHAINS.get(source_chain)
        if not chain:
            return Decimal("50")  # Conservative default
        
        base_costs = {
            ChainLayer.LAYER_1: Decimal("20"),  # ~$20 on mainnet
            ChainLayer.LAYER_2: Decimal("0.50"),  # ~$0.50 on L2
            ChainLayer.LAYER_3: Decimal("0.10"),  # ~$0.10 on L3
        }
        
        source_cost = base_costs.get(chain.layer, Decimal("10"))
        
        if is_cross_chain:
            target_chain_info = SUPPORTED_CHAINS.get(target_chain)
            if target_chain_info:
                target_cost = base_costs.get(target_chain_info.layer, Decimal("10"))
            else:
                target_cost = Decimal("10")
            return source_cost + target_cost
        
        return source_cost * 2  # Two swaps on same chain

    def _get_max_trade_amount(
        self,
        token: str,
        chain_id: int,
        dex_name: str,
        liquidity_data: Dict,
    ) -> Decimal:
        """Get maximum trade amount based on liquidity."""
        try:
            pool_liquidity = liquidity_data.get(chain_id, {}).get(dex_name, {}).get(token, 0)
            # Max 2% of pool liquidity to minimize price impact
            return Decimal(str(pool_liquidity)) * Decimal("0.02")
        except (KeyError, TypeError):
            return Decimal("1000")  # Default $1000 max

    def _calculate_confidence(self, opp: ArbitrageOpportunity) -> float:
        """Calculate confidence score for opportunity."""
        # Base confidence from profit margin
        profit_confidence = min(1.0, opp.profit_bps / 100)  # Max at 1% profit
        
        # Penalty for cross-chain (more risk)
        cross_chain_penalty = 0.2 if opp.is_cross_chain else 0.0
        
        # Penalty for low net profit
        net_profit_score = min(1.0, float(opp.net_profit_estimate) / 50)  # Max at $50 profit
        
        confidence = (profit_confidence * 0.4 + net_profit_score * 0.4) * (1 - cross_chain_penalty)
        
        return max(0.1, min(0.95, confidence))

    def validate_opportunity(
        self,
        signal: TradingSignal,
        current_prices: Dict[str, Decimal],
    ) -> bool:
        """Validate arbitrage opportunity is still profitable."""
        if not signal.is_valid():
            return False
        
        metadata = signal.metadata.get('opportunity', {})
        source_chain = metadata.get('source_chain')
        target_chain = metadata.get('target_chain')
        
        # Get current prices
        source_price = current_prices.get(f"{source_chain}:{signal.token_in}")
        target_price = current_prices.get(f"{target_chain}:{signal.token_in}")
        
        if not source_price or not target_price:
            return False
        
        # Recalculate profit
        if source_price < target_price:
            current_profit_bps = int(((target_price - source_price) / source_price) * 10000)
        else:
            current_profit_bps = int(((source_price - target_price) / target_price) * 10000)
        
        # Require at least 70% of original expected profit
        return current_profit_bps >= signal.expected_profit_bps * 0.7

    def _generate_signal_id(self) -> str:
        """Generate unique signal ID."""
        return f"ARB-{secrets.token_hex(8).upper()}"

    def _generate_opportunity_id(self) -> str:
        """Generate unique opportunity ID."""
        return f"OPP-{secrets.token_hex(8).upper()}"


